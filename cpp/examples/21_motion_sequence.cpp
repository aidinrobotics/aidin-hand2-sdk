int main(int argc, char** argv)
{
  std::signal(SIGINT, [](int) { g_shutdown.store(true); });

  const HandSide side = (argc > 1 && std::string(argv[1]) == "left") ? HandSide::Left : HandSide::Right;

  HandManager manager;
  int         exit_code = 0;

  try {
    HandConfig config{argc > 2 ? argv[2] : "can0", side};
    config.control_rate = kControlRate;
    config.auto_home    = false;

    Hand hand = manager.create(config);
    hand.connect();

    hand.set_max_effort(1000.0);

    ControllerConfig controller;
    controller.joint_position_controller.filter_enabled = true;
    controller.joint_position_controller.cutoff_freq    = 5.0;
    controller.joint_position_controller.deadband       = 0.0;
    hand.set_controller_config(controller);

    hand.run();
    hand.home();

    auto next = std::chrono::steady_clock::now();

    for (int lap = 1; !g_shutdown.load(); ++lap) {
      for (std::size_t i = 0; i < kMotion.size() && !g_shutdown.load(); ++i) {
        const Waypoint& from = kMotion[i];
        const Waypoint& to   = kMotion[(i + 1) % kMotion.size()];
        const int steps = static_cast<int>(from.dwell_sec * kControlRate + 0.5);

        std::printf("\r\033[K  lap %d  %-14s  %4.0f ms  %d steps", lap, from.label,
                    from.dwell_sec * 1000.0, steps);
        std::fflush(stdout);

        for (int step = 1; step <= steps && !g_shutdown.load(); ++step) {
          const double alpha = static_cast<double>(step) / steps;

          JointPositionCommand command;
          for (std::size_t j = 0; j < kActiveJointCount; ++j) {
            const double deg = from.target_deg[j] + (to.target_deg[j] - from.target_deg[j]) * alpha;
            command.target[j] = deg * kDegToRad;
          }
          hand.set_command(command);

          next += kStep;
          std::this_thread::sleep_until(next);
        }
      }
    }
    std::printf("\n");

    hand.set_command(Idle{});
    hand.stop();
  } catch (const Exception& error) {
    std::printf("\nfailed: %s: %s\n", to_string(error.code()), error.what());
    exit_code = 1;
  }

  return exit_code;
}
